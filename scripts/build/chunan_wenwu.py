def apply(rows):
    for town, bookname, name, struct, length, era, loc, page in DATA:
        hits=[r for r in rows if (r.get('dist'),r.get('town'),r.get('name'))==('淳安县',town,name)]
        assert len(hits)<=1,(town,name)
        if hits:
            r=hits[0]
            if r.get('level')=='尚未定级（待核实）': r['level']='尚未定级（已核实）'
            for key,value in [('struct',struct),('len',length),('era',era)]:
                if r.get(key) in (None,'','—'):r[key]=value
            if name=='桐坑口村解麟桥':
                extra='书中称獬麟桥，记长18.5米、民国十年（1921）建；与历史建筑档案长18米存在差异'
            elif name=='进德桥':
                r['note']=(r.get('note') or '').replace('年代及文保等级待核','文保等级待核')
                extra='书据宗谱记清顺治二年（1645）始建，1946年及2002年维修'
            elif name=='登瀛桥': extra='书记清乾隆十一年（1746）重修'
            else: extra=''
        else:
            r=dict(dist='淳安县',town=town,name=name,struct=struct,len=length,era=era,loc=loc,level='尚未定级（已核实）',doc='—',src=SOURCE,srcs=[SOURCE],note='',commons=None)
            rows.append(r); extra=''
        note=f'据《文物叙略》印刷页第{page}页';note+=('；'+extra if extra else '')
        if note not in (r.get('note') or ''):r['note']=(r.get('note')+'；' if r.get('note') else '')+note
        if SOURCE not in r.setdefault('srcs',[]):r['srcs'].append(SOURCE)
    return rows
